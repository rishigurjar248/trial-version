create table if not exists public.products (
  id bigint primary key,
  page bigint,
  name text not null default '',
  brand text not null default '',
  category text not null default 'All Deals',
  price numeric not null default 0,
  payment_type text not null default 'full',
  partial_payment_amount numeric not null default 0,
  mrp numeric not null default 0,
  old_price numeric not null default 0,
  discount numeric not null default 0,
  rating numeric not null default 4.3,
  reviews text not null default '0',
  review_count integer not null default 0,
  image text not null default '',
  gallery_images jsonb not null default '[]'::jsonb,
  images jsonb not null default '[]'::jsonb,
  key_points jsonb not null default '[]'::jsonb,
  description text not null default '',
  is_top10 boolean not null default false,
  top10_rank integer,
  storefront_rank integer,
  is_active boolean not null default true,
  return_eligible boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.products add column if not exists return_eligible boolean not null default true;
alter table public.products add column if not exists updated_at timestamptz not null default now();
alter table public.products add column if not exists storefront_rank integer;
alter table public.products add column if not exists payment_type text not null default 'full';
alter table public.products add column if not exists partial_payment_amount numeric not null default 0;

do $$
begin
  if not exists (
    select 1
    from pg_constraint
    where conname = 'products_payment_terms_check'
      and conrelid = 'public.products'::regclass
  ) then
    alter table public.products
      add constraint products_payment_terms_check
      check (
        payment_type in ('full', 'partial')
        and partial_payment_amount >= 0
        and (
          payment_type = 'full'
          or (partial_payment_amount > 0 and partial_payment_amount < price)
        )
      );
  end if;
end $$;

create table if not exists public.product_images (
  id bigint generated by default as identity primary key,
  product_id bigint not null references public.products(id) on delete cascade,
  image_url text not null,
  position integer not null check (position between 1 and 5),
  created_at timestamptz not null default now(),
  unique (product_id, position)
);

create index if not exists product_images_product_idx
  on public.product_images (product_id, position);

alter table public.products enable row level security;
alter table public.product_images enable row level security;

drop policy if exists "Public can read active products" on public.products;
create policy "Public can read active products"
on public.products
for select
to anon, authenticated
using (is_active = true);

drop policy if exists "Public can read active product images" on public.product_images;
create policy "Public can read active product images"
on public.product_images
for select
to anon, authenticated
using (
  exists (
    select 1 from public.products p
    where p.id = product_images.product_id
      and p.is_active = true
  )
);

create index if not exists products_active_top10_idx
  on public.products (is_active, top10_rank);

create index if not exists products_active_storefront_idx
  on public.products (is_active, storefront_rank);

create index if not exists products_category_idx
  on public.products (category);

